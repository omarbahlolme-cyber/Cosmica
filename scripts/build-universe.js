/* Build only the spatial/studio artifacts; --check never writes files. */
const fs = require("node:fs");
const path = require("node:path");
const {
  MANIFEST_PATH,
  PAGE_ASSETS,
  RENDERER_PATH,
  checkUniverseAssets,
  createManifest,
  lockedBuildDependencies,
  serializeManifest,
  updatePageAssetVersions,
} = require("./lib/universe-assets");

const buildUniverse = (root, { check = false } = {}) => {
  const esbuild = require("esbuild");
  const dependencies = lockedBuildDependencies(root);
  if (esbuild.version !== dependencies.esbuild.version) {
    throw new Error("Installed renderer dependencies differ from package-lock.json. Run npm ci.");
  }
  const rendererPath = path.join(root, "frontend", RENDERER_PATH);
  const result = esbuild.buildSync({
    absWorkingDir: root,
    entryPoints: ["frontend/ui/cosmic-scene.js"],
    outfile: rendererPath,
    write: false,
    bundle: true,
    minify: true,
    format: "iife",
    globalName: "CosmicaRenderer",
    target: ["es2020"],
    legalComments: "eof",
    banner: { js: "/* Generated by npm run build:universe from cosmic-scene.js. */" },
  });
  const rendererBytes = Buffer.from(result.outputFiles[0].contents);
  if (check) {
    const problems = checkUniverseAssets(root);
    if (!fs.existsSync(rendererPath) || !fs.readFileSync(rendererPath).equals(rendererBytes)) {
      problems.unshift("Served renderer differs from a fresh build");
    }
    if (problems.length) throw new Error(`${problems.join("\n")}\nRun npm run build:universe and review the focused artifacts.`);
    return;
  }

  const manifest = createManifest(root, rendererBytes);
  // Compute every output first, so invalid HTML cannot leave a partly updated build.
  const outputs = [
    [rendererPath, rendererBytes],
    [path.join(root, MANIFEST_PATH), serializeManifest(manifest)],
    ...Object.keys(PAGE_ASSETS).map((pagePath) => [
      path.join(root, pagePath),
      updatePageAssetVersions(fs.readFileSync(path.join(root, pagePath), "utf8"), pagePath, manifest),
    ]),
  ];
  for (const [filePath, content] of outputs) {
    const bytes = Buffer.isBuffer(content) ? content : Buffer.from(content);
    if (!fs.existsSync(filePath) || !fs.readFileSync(filePath).equals(bytes)) {
      fs.writeFileSync(filePath, bytes);
    }
  }
};

if (require.main === module) {
  try {
    if (process.argv.slice(2).some((argument) => argument !== "--check")) {
      throw new Error("Usage: node scripts/build-universe.js [--check]");
    }
    const check = process.argv.includes("--check");
    buildUniverse(path.resolve(__dirname, ".."), { check });
    console.log(check ? "PASS [universe-build] renderer and asset versions are current" : "Built renderer, asset manifest, and focused page versions.");
  } catch (error) {
    console.error(`FAIL [universe-build] ${error.message}`);
    process.exitCode = 1;
  }
}

module.exports = { buildUniverse };
