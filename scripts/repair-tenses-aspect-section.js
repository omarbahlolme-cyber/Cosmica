const applyTensesAspectUpdates = (cards, updates) => {
  if (!Array.isArray(cards) || !Array.isArray(updates)) {
    return 0;
  }
  let changed = 0;
  updates.forEach((update, index) => {
    if (!cards[index] || !update) {
      return;
    }
    const card = cards[index];
    let cardChanged = false;
    Object.entries(update).forEach(([key, value]) => {
      if (JSON.stringify(card[key]) !== JSON.stringify(value)) {
        card[key] = value;
        cardChanged = true;
      }
    });
    if (cardChanged) {
      changed += 1;
    }
  });
  return changed;
};

const repairTensesAspectInPack = (pack, worldKey) => {
  const updates = TENSES_ASPECT_UPDATES[worldKey];
  const cards = pack?.grammar?.cards?.["Tenses & Aspect"];
  if (!updates || !Array.isArray(cards)) {
    return 0;
  }
  return applyTensesAspectUpdates(cards, updates);
};

